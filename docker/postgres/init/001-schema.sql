CREATE TABLE IF NOT EXISTS housing_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano INTEGER NOT NULL,
    trimestre SMALLINT NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    fecha DATE NOT NULL,
    precio_m2 NUMERIC NOT NULL CHECK (precio_m2 > 0),
    regimen TEXT NOT NULL,
    comunidad_autonoma TEXT NOT NULL,
    CONSTRAINT uq_housing_prices_period UNIQUE (ano, trimestre),
    CONSTRAINT ck_housing_prices_period_date CHECK (
        date_part('year', fecha)::INTEGER = ano
        AND date_part('quarter', fecha)::INTEGER = trimestre
    )
);

CREATE INDEX IF NOT EXISTS ix_housing_prices_fecha ON housing_prices (fecha);

